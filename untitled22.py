import re
from nltk.util import ngrams

sentence = "AI is simulation of human intelligence by machine. It includes expert systems, NLP, speech recognition and machine vision"
words = re.findall(r"\b\w+\b", sentence.lower())

bigrams = list(ngrams(words, 2))
trigrams = list(ngrams(words, 3))

print("words:")
print(words)

print("\nBigrams:")
for bigram in bigrams:
    print(" ".join(bigram))

print("\nTrigrams:")
for trigram in trigrams:
    print(" ".join(trigram))